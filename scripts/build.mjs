// Zero dependency build: emits dist/chrome and dist/firefox from extension/ (v2).
// Usage: node scripts/build.mjs
import {
  cpSync,
  copyFileSync,
  mkdirSync,
  rmSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "extension");
const dist = join(root, "dist");
const packageInfo = JSON.parse(
  readFileSync(join(root, "package.json"), "utf8"),
);
function emit(variant, manifestName) {
  const out = join(dist, variant);
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  cpSync(src, out, {
    recursive: true,
    filter: (p) => {
      const base = p.split(/[\\/]/).pop();
      if (base.startsWith("_")) {
        return false;
      }
      return (
        !p.endsWith("manifest.json") && !p.endsWith("manifest.firefox.json")
      );
    },
  });
  copyFileSync(join(src, manifestName), join(out, "manifest.json"));
  const note =
    "Built from extension/ on " +
    new Date().toISOString() +
    " for " +
    variant +
    ".\n";
  writeFileSync(join(out, "BUILD.txt"), note);
  console.log("built " + out);
}
mkdirSync(dist, { recursive: true });
emit("chrome", "manifest.json");
emit("firefox", "manifest.firefox.json");
function emitUserscript() {
  const output = join(root, "userscript", "ralgrum.user.js");
  const updateUrl =
    "https://github.com/kekkodance/ralgrum-browser-extension/raw/refs/heads/master/userscript/ralgrum.user.js";
  const sources = [
    "extension/content/detectors.js",
    "userscript/menu.js",
    "extension/content/spa-navigation.js",
    "extension/content/deezer-metadata.js",
    "extension/content/soundcloud-metadata.js",
    "extension/content/toast.js",
    "extension/content/content-deezer.js",
    "extension/content/content-soundcloud.js",
  ];
  const runNumber = process.env.GITHUB_RUN_NUMBER;
  const userscriptVersion = /^\d+$/.test(runNumber || "")
    ? packageInfo.version + "." + runNumber
    : packageInfo.version;
  const iconUrl =
    "https://raw.githubusercontent.com/kekkodance/ralgrum-browser-extension/master/extension/icons/icon128.png?v=" +
    userscriptVersion;
  const metadata = [
    "// ==UserScript==",
    "// @name         ralgruM Browser Integration",
    "// @namespace    https://github.com/kekkodance/ralgrum-browser-extension",
    "// @version      " + userscriptVersion,
    "// @description  Open Deezer and SoundCloud tracks, albums, playlists, and artists in ralgruM.",
    "// @icon         " + iconUrl,
    "// @match        https://www.deezer.com/*",
    "// @match        https://*.deezer.com/*",
    "// @match        https://soundcloud.com/*",
    "// @match        https://*.soundcloud.com/*",
    "// @run-at       document-idle",
    "// @grant        GM_registerMenuCommand",
    "// @grant        GM.registerMenuCommand",
    "// @updateURL    " + updateUrl,
    "// @downloadURL  " + updateUrl,
    "// ==/UserScript==",
  ].join("\n");
  const style = readFileSync(join(src, "content", "toast.css"), "utf8");
  const logoDataUrl =
    "data:image/png;base64," +
    readFileSync(join(src, "icons", "icon32.png")).toString("base64");
  const content = sources
    .map((file) => {
      return (
        "/* Source: " +
        file +
        " */\n" +
        readFileSync(join(root, file), "utf8").trimEnd()
      );
    })
    .join("\n\n");
  const styleSetup =
    "(function () {\n" +
    "  window.RalgrumEmbeddedLogoUrl = " +
    JSON.stringify(logoDataUrl) +
    ";\n" +
    '  var style = document.createElement("style");\n' +
    "  style.textContent = " +
    JSON.stringify(style) +
    ";\n" +
    "  (document.head || document.documentElement).appendChild(style);\n" +
    "})();";

  mkdirSync(join(root, "userscript"), { recursive: true });
  writeFileSync(
    output,
    metadata +
      "\n\n// Generated by scripts/build.mjs from extension/content/.\n" +
      styleSetup +
      "\n\n" +
      content +
      "\n",
    "utf8",
  );
  console.log("built " + output);
}
emitUserscript();
console.log("done. Zip dist/chrome and dist/firefox for store uploads.");
